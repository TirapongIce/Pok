function parseLaoHistoryToPayloads() {
  const blocks = parseLaoHistoryRaw()
    .split("ตรวจหวยลาว")
    .map((b) => b.trim())
    .filter(Boolean);
  const results = [];
  for (const block of blocks) {
    const headerMatch = block.match(/งวดประจำวันที่\s+(\d+)\s+([ก-๙]+)\s+(\d{4})/);
    const four = block.match(/เลข 4 ตัว\s*:\s*([0-9]{2,6})/);
    const three = block.match(/เลข 3 ตัว\s*:\s*([0-9]{2,3})/);
    const two = block.match(/เลข 2 ตัว\s*:\s*([0-9]{1,2})/);
    if (!headerMatch) continue;
    const day = Number(headerMatch[1]);
    const month = monthMap[headerMatch[2]];
    const yearBE = Number(headerMatch[3]);
    if (!month || !yearBE) continue;
    const year = yearBE - 543;
    const drawDate = new Date(Date.UTC(year, month - 1, day)).toISOString().slice(0, 10);
    if (!four || !three || !two) {
      continue; // skip งดออกรางวัล
    }
    results.push({
      lotteryCode: "lao-lottery",
      drawDate,
      firstPrize: four[1].padStart(4, "0"),
      threeDigits: three[1].padStart(3, "0"),
      twoDigits: two[1].padStart(2, "0")
    });
  }
  return results;
}

async function main() {
  if (!pool) {
    console.error("Database is not configured");
    process.exit(1);
  }
  const payloads = parseLaoHistoryToPayloads();
  let success = 0;
  for (const payload of payloads) {
    try {
      await upsertLotteryResult(payload);
      success += 1;
    } catch (err) {
      console.error("Failed to upsert", payload.drawDate, err.message || err);
    }
  }
  console.log(`Inserted/updated ${success} Lao lottery results`);
  await pool.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
